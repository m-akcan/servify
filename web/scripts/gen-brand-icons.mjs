/**
 * Copies the brand logos Servify uses from simple-icons (CC0-1.0) into src/components/brandIcons.ts,
 * so the app has no runtime dependency on the full icon set. Re-run after adding a key below.
 *   node web/scripts/gen-brand-icons.mjs
 */
import * as si from 'simple-icons';
import { writeFileSync, existsSync } from 'node:fs';

// Service icon key → simple-icons export
const MAP = {
  postgres: 'siPostgresql', redis: 'siRedis', mysql: 'siMysql', mariadb: 'siMariadb', mongo: 'siMongodb',
  bucket: 'siMinio', minio: 'siMinio', wave: 'siTraefikproxy', traefik: 'siTraefikproxy', nginx: 'siNginx', globe: 'siNginx',
  table: 'siAdminer', flow: 'siN8n', pulse: 'siUptimekuma', spark: 'siOllama', node: 'siNodedotjs', python: 'siPython',
  caddy: 'siCaddy', github: 'siGithub', git: 'siGit', docker: 'siDocker', go: 'siGo', rust: 'siRust', deno: 'siDeno',
  ruby: 'siRuby', php: 'siPhp', vite: 'siVite', next: 'siNextdotjs', bun: 'siBun', rabbitmq: 'siRabbitmq',
  grafana: 'siGrafana', prometheus: 'siPrometheus', elasticsearch: 'siElasticsearch', kafka: 'siApachekafka',
  static: 'siHtml5', meilisearch: 'siMeilisearch', clickhouse: 'siClickhouse', keycloak: 'siKeycloak',
  gitlab: 'siGitlab', gitea: 'siGitea', discord: 'siDiscord', telegram: 'siTelegram', cloudflare: 'siCloudflare',
  letsencrypt: 'siLetsencrypt', supabase: 'siSupabase', alpine: 'siAlpinelinux', ubuntu: 'siUbuntu', debian: 'siDebian',
};

const lum = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};

const out = {};
for (const [key, exp] of Object.entries(MAP)) {
  const icon = si[exp];
  if (!icon) throw new Error(`simple-icons has no ${exp}`);
  out[key] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path, ...(lum(icon.hex) < 0.045 ? { neutral: true } : {}) };
}

const body = `/* Generated by web/scripts/gen-brand-icons.mjs from simple-icons (CC0-1.0). Brand names and logos belong to their owners. */
export type BrandIcon = { title: string; hex: string; path: string; neutral?: boolean };
export const BRAND_ICONS: Record<string, BrandIcon> = ${JSON.stringify(out, null, 0).replace(/},"/g, '},\n  "')};
`;
writeFileSync(new URL('../src/components/brandIcons.ts', import.meta.url), body);
// The landing page (site/) uses the same logos when it is present.
const site = new URL('../../site/', import.meta.url);
if (existsSync(site)) writeFileSync(new URL('brand-icons.json', site), JSON.stringify(out));
console.log(`wrote ${Object.keys(out).length} icons`);
